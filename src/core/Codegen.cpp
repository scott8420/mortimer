std::string cpp_string(const std::string& s) {
    std::string o = "\"";
    for (unsigned char c : s) {
        switch (c) {
            case '\\': o += "\\\\"; break;
            case '"':  o += "\\\""; break;
            case '\n': o += "\\n"; break;
            case '\t': o += "\\t"; break;
            case '\r': o += "\\r"; break;
            default:
                if (c < 0x20 || c == 0x7f) {
                    char b[8];
                    std::snprintf(b, sizeof b, "\\%03o", c);
                    o += b;
                } else {
                    o += static_cast<char>(c);
                }
        }
    }
    return o + "\"";
}

std::string Hook::decl() const { return ret + " " + name + "(" + params + ")"; }

std::vector<Hook> hooks_of(const Form& f) {
    std::vector<Hook> out;
    walk_members(f.root, [&](const Node& n, const Node*) {
        const WidgetSpec* w = find_widget(n.type);
        if (!w) return;
        for (const auto& h : n.signals) {
            const SignalSpec* s = find_signal(*w, h.signal);
            if (!s) continue;
            std::string params = s->params;
            if (params == "{item}") {   // s006: a row of the widget's model
                const auto it = n.props.find("model");
                const std::string item = it != n.props.end() && std::holds_alternative<std::string>(it->second)
                                             ? std::get<std::string>(it->second) + "Item" : "Glib::ObjectBase";
                params = h.signal == "selected" && view_selection(n) == "multiple"
                             ? "const std::vector<Glib::RefPtr<" + item + ">>& items"   // s007: every picked row
                             : "const Glib::RefPtr<" + item + ">& item";
            } else if (params == "{item_field}") {   // s007: an edited cell -- its row and its field
                const auto it = n.props.find("model");
                const std::string item = it != n.props.end() && std::holds_alternative<std::string>(it->second)
                                             ? std::get<std::string>(it->second) + "Item" : "Glib::ObjectBase";
                params = "const Glib::RefPtr<" + item + ">& item, const std::string& field";
            }
            out.push_back({hook_name(n, h), s->ret, params, s->ret_default, n.id, n.type,
                           h.signal, h.required});
        }
    });
    // s011 m2: a ListView row's widgets -- each hook hands you that row's item.
    walk_members(f.root, [&](const Node& v, const Node*) {
        if (v.type != "ListView" || !view_row(v)) return;
        const auto it = v.props.find("model");
        const std::string item = it != v.props.end() && std::holds_alternative<std::string>(it->second)
                                     ? std::get<std::string>(it->second) + "Item" : "Glib::ObjectBase";
        walk(*view_row(v), [&](const Node& n, const Node*) {
            const WidgetSpec* w = find_widget(n.type);
            if (!w) return;
            for (const auto& h : n.signals)
                if (const SignalSpec* s = find_signal(*w, h.signal))
                    out.push_back({hook_name(n, h), s->ret, "const Glib::RefPtr<" + item + ">& item", s->ret_default,
                                   n.id, n.type, h.signal, h.required});
        });
    });
    // s003: each action is a hook too (widget = the action's name, type "Action").
    for (const auto& a : f.actions)
        if (a.opens.empty())   // s010: one that opens a window has no hook
            out.push_back({action_hook(a), "void", "", "", a.name, "Action", "activate", a.required});
    // s005: each file dialog's answer is a hook; Cancel is one too when ticked.
    for (const auto& d : f.files) {
        out.push_back({file_chosen_hook(d), "void",
                       d.mode == "open_multiple" ? "const std::vector<std::string>& paths"
                                                 : "const std::string& path",
                       "", d.name, "FileDialog", "chosen", d.required});
        if (d.cancel)
            out.push_back({file_cancelled_hook(d), "void", "", "", d.name, "FileDialog", "cancelled", false});
    }
    return out;
}

std::string override_decl(const Hook& h) {
    return "    " + h.decl() + " override;" + (h.required ? "   // REQUIRED" : "");
}

std::string override_def(const Hook& h, const std::string& cls) {
    std::string body = h.ret == "void" ? "" : "    return " + h.ret_default + ";\n";
    return h.ret + " " + cls + "::" + h.name + "(" + h.params + ") {\n" + body + "}\n";
}

// s005 -- one file dialog's choose_<name>(): build the Gtk::FileDialog, ask,
// and deliver the answer to its hook. The rules it keeps:
//   * one at a time -- asking again while it's up is refused (logged), not stacked;
//   * the answer checks the window's token first -- if the window went, nothing runs;
//   * Cancel / Escape (DialogError DISMISSED / CANCELLED) is not an error: it goes
//     to on_<name>_cancelled() when ticked, else nowhere; a real failure is logged
//     and then treated as a cancel, so a hook waiting on the answer always gets one.
static std::string file_chooser_def(const Form& f, const FileDef& d, const std::string& ui) {
    static const std::map<std::string, std::pair<std::string, std::string>> calls = {
        {"open", {"open", "open_finish"}},
        {"open_multiple", {"open_multiple", "open_multiple_finish"}},
        {"save", {"save", "save_finish"}},
        {"folder", {"select_folder", "select_folder_finish"}},
    };
    const auto call = calls.count(d.mode) ? calls.at(d.mode) : calls.at("open");
    const bool many = d.mode == "open_multiple";
    const std::string who = f.name + ": " + d.name;
    std::ostringstream c;
    c << "\n// ── file dialog " << d.name << " (" << d.mode << ") ──\n"
      << "void " << ui << "::" << file_chooser(d) << "(const std::string& initial) {\n"
      << "    if (m_files[" << cpp_string(d.name) << "]) {\n"
      << "        if (auto lg = log::get(log::Area::Ui)) lg->info(" << cpp_string(who + ": already open") << ");\n"
      << "        return;\n"
      << "    }\n"
      << "    auto dialog = Gtk::FileDialog::create();\n"
      << "    dialog->set_modal(true);\n";
    if (!d.title.empty()) c << "    dialog->set_title(" << cpp_string(d.title) << ");\n";
    if (!d.accept.empty()) c << "    dialog->set_accept_label(" << cpp_string(d.accept) << ");\n";
    if (!d.filters.empty() && d.mode != "folder") {
        c << "    {\n"
          << "        auto filters = Gio::ListStore<Gtk::FileFilter>::create();\n";
        for (const auto& row : d.filters) {
            const FileFilterRow r = parse_file_filter(row);
            if (!r.ok) continue;
            c << "        {\n"
              << "            auto ff = Gtk::FileFilter::create();\n"
              << "            ff->set_name(" << cpp_string(r.label) << ");\n";
            for (const auto& p : r.patterns)
                c << "            ff->" << (p.find('/') != std::string::npos ? "add_mime_type(" : "add_pattern(")
                  << cpp_string(p) << ");\n";
            c << "            filters->append(ff);\n"
              << "        }\n";
        }
        c << "        dialog->set_filters(filters);\n"
          << "    }\n";
    }
    c << "    if (!initial.empty()) {\n"
      << "        auto at = Gio::File::create_for_path(initial);\n"
      << "        if (Glib::file_test(initial, Glib::FileTest::IS_DIR)) dialog->set_initial_folder(at);\n";
    if (d.mode == "save")
        c << "        else if (initial.find('/') == std::string::npos) dialog->set_initial_name(initial);\n";
    c << "        else dialog->set_initial_file(at);   // its folder, and its name\n"
      << "    }\n"
      << "    auto cancel = Gio::Cancellable::create();\n"
      << "    m_files[" << cpp_string(d.name) << "] = cancel;\n"
      << "    dialog->" << call.first << "(*this, [this, alive = std::weak_ptr<bool>(m_alive), dialog]\n"
      << "                         (const Glib::RefPtr<Gio::AsyncResult>& result) {\n"
      << "        if (alive.expired()) return;   // the window went first: nobody to tell\n"
      << "        m_files.erase(" << cpp_string(d.name) << ");\n";
    if (many) c << "        std::vector<std::string> paths;\n";
    else      c << "        std::string path;\n";
    c << "        try {\n";
    if (many)
        c << "            for (const auto& file : dialog->" << call.second << "(result))\n"
          << "                if (file) paths.push_back(file->get_path().empty() ? file->get_uri() : file->get_path());\n";
    else
        c << "            if (auto file = dialog->" << call.second << "(result))\n"
          << "                path = file->get_path().empty() ? file->get_uri() : file->get_path();\n";
    c << "        } catch (const Gtk::DialogError& e) {\n"
      << "            if (e.code() == Gtk::DialogError::FAILED)\n"
      << "                if (auto lg = log::get(log::Area::Ui)) lg->error(" << cpp_string(who + ": {}") << ", e.what());\n"
      << "        } catch (const Glib::Error& e) {\n"
      << "            if (auto lg = log::get(log::Area::Ui)) lg->error(" << cpp_string(who + ": {}") << ", e.what());\n"
      << "        }\n"
      << "        if (!" << (many ? "paths" : "path") << ".empty()) " << file_chosen_hook(d)
      << "(" << (many ? "paths" : "path") << ");\n";
    if (d.cancel) c << "        else " << file_cancelled_hook(d) << "();\n";
    c << "    }, cancel);\n"
      << "}\n";
    return c.str();
}

// s010 -- an action that OPENS a window (another form, or the shortcuts window).
// The window is built the first time it's asked for and kept: it hides on close
// (the X), so every later ask re-presents the SAME window -- the dialog-lifetime
// stone (docs/resources-and-dialog-lifetime.md). It goes when this window goes.
static bool opens_any(const Form& f) {
    for (const auto& a : f.actions) if (!a.opens.empty()) return true;
    return false;
}
static std::string opens_class(const ActionDef& a, const AppInfo& app) {
    return a.opens == kShortcutsTarget ? "::" + app.ns + "::ui::ShortcutsWindow" : "::" + app.ns + "::" + a.opens;
}
// The header only names the classes (forward declarations): a std::unique_ptr
// to one is fine as long as the destructor -- in the .cpp -- sees it whole. So
// two forms can open each other without their headers including each other.
static std::string opens_forward(const Form& f, const AppInfo& app) {
    std::set<std::string> forms;
    bool shortcuts = false;
    for (const auto& a : f.actions) {
        if (a.opens.empty()) continue;
        if (a.opens == kShortcutsTarget) shortcuts = true;
        else forms.insert(a.opens);
    }
    if (forms.empty() && !shortcuts) return "";
    std::string o = "// s010: the windows this one opens (built on first ask, then kept).\n";
    if (!forms.empty()) {
        o += "namespace " + app.ns + " {\n";
        for (const auto& x : forms) o += "class " + x + ";\n";
        o += "}\n";
    }
    if (shortcuts) o += "namespace " + app.ns + "::ui {\nclass ShortcutsWindow;\n}\n";
    return o + "\n";
}
static std::string opens_members(const Form& f, const AppInfo& app) {
    std::string o;
    for (const auto& a : f.actions)
        if (!a.opens.empty())
            o += "    std::unique_ptr<" + opens_class(a, app) + "> " + opens_member(a) + ";   // win." +
                 gio_action_name(a.name) + " opens it\n";
    return o;
}
static std::string opens_includes(const Form& f) {
    std::set<std::string> inc;
    for (const auto& a : f.actions) {
        if (a.opens.empty()) continue;
        inc.insert(a.opens == kShortcutsTarget ? "generated/Shortcuts.hpp" : a.opens + ".hpp");
    }
    std::string o;
    for (const auto& x : inc) o += "#include \"" + x + "\"\n";
    return o;
}
static std::string opens_activate(const ActionDef& a, const AppInfo& app) {
    const std::string m = opens_member(a);
    return "        // It opens " + (a.opens == kShortcutsTarget ? std::string("the keyboard-shortcuts window") : a.opens) +
           ": built the first time, then kept -- the X hides it, so\n"
           "        // the next ask shows the same window. It goes when this window goes.\n"
           "        m_hooks.push_back(a->signal_activate().connect([this](const Glib::VariantBase&) {\n"
           "            if (!" + m + ") {\n"
           "                " + m + " = std::make_unique<" + opens_class(a, app) + ">();\n"
           "                " + m + "->set_hide_on_close(true);\n"
           "            }\n"
           "            " + m + "->set_transient_for(*this);\n"
           "            " + m + "->present();\n"
           "        }));\n";
}

// s011 -- each ListView's row class, nested in <Form>Ui: its widgets are plain
// Gtk:: members (many rows exist at once, so no registry names), built in its
// constructor exactly as build_ui() builds the form; bind() shows an item.
static std::string ui_of(const Form& f) { return f.name + "Ui"; }

static std::vector<std::pair<const Node*, const ModelDef*>> list_views(const Form& f) {
    std::vector<std::pair<const Node*, const ModelDef*>> out;
    walk_members(f.root, [&](const Node& n, const Node*) {
        if (n.type != "ListView") return;
        const ModelDef* md = model_of(f, n);
        if (md && view_row(n)) out.push_back({&n, md});
    });
    return out;
}

// s011 m2 -- what a row's widgets do. A bound input writes its field back
// (only when it differs), then the view's edited(item, field) fires; the
// widget's own ticked hooks get the row's item. Nothing runs while bind() is
// filling the row, between items, or once the form is going.
static std::string row_wiring(const Form& f, const Node& v, const ModelDef& md) {
    std::ostringstream c;
    const bool edited = row_writes(v, md);
    walk(*view_row(v), [&](const Node& n, const Node* parent) {
        const WidgetSpec* w = find_widget(n.type);
        const std::string obj = parent ? "m_" + n.id + "." : "";
        const FieldDef* fd = nullptr;
        for (const auto& x : md.fields) if (x.name == bound_field(n)) fd = &x;
        const bool writes = fd && bind_writes(n.type, fd->type);
        // The signal a write-back rides on, and how to read the widget's value.
        std::string wsig, read;
        if (writes) {
            if (n.type == "CheckButton") { wsig = "toggled"; read = obj + "get_active()"; }
            else if (n.type == "Switch") { wsig = "active_changed"; read = obj + "get_active()"; }
            else if (n.type == "Entry")  { wsig = "changed"; read = "std::string(" + obj + "get_text())"; }
            else { wsig = "value_changed";
                   read = fd->type == "int" ? "static_cast<std::int64_t>(std::llround(" + obj + "get_value()))"
                                            : obj + "get_value()"; }
        }
        if (fd && !writes && n.type == "Entry")
            c << "    " << obj << "set_editable(false);   // shows " << fd->name << " (" << (fd->type == "int" ? "an " : "a ") << fd->type << "); not written back\n";
        std::vector<std::string> sigs;
        if (writes) sigs.push_back(wsig);
        for (const auto& h : n.signals) if (h.signal != wsig) sigs.push_back(h.signal);
        for (const auto& sname : sigs) {
            const SignalSpec* s = find_signal(*w, sname);
            if (!s) continue;
            const SignalHook* hk = nullptr;
            for (const auto& h : n.signals) if (h.signal == sname) hk = &h;
            c << "    // " << n.id << " " << sname
              << (writes && sname == wsig ? ": writes " + fd->name + " back" + (hk ? ", then its hook" : "") : ": its hook")
              << "\n"
              << "    " << obj << s->connect << ".connect([this] {\n"
              << "        if (m_binding || !m_item || !*m_alive) return;\n";
            if (writes && sname == wsig) {
                c << "        if (m_item->" << fd->name << " != " << read << ") {\n"
                  << "            m_item->" << fd->name << " = " << read << ";\n";
                if (edited) c << "            m_ui->m_" << v.id << "_edited.emit(m_item, " << cpp_string(fd->name) << ");\n";
                c << "        }\n";
            }
            if (hk) c << "        m_ui->" << hook_name(n, *hk) << "(m_item);\n";
            c << "    });\n";
        }
    });
    return c.str();
}

static std::string row_classes_header(const Form& f) {
    std::ostringstream h;
    for (const auto& [v, md] : list_views(f)) {
        const Node& row = *view_row(*v);
        const WidgetSpec* rw = find_widget(row.type);
        const std::string rc = row_class(*v);
        h << "    // ── " << v->id << "'s row ── GTK builds one per VISIBLE row and refills it as\n"
          << "    // you scroll (bind). Its widgets are its members, not the form's.\n"
          << "    class " << rc << " : public " << rw->gtk_class << " {\n"
          << "    public:\n"
          << "        explicit " << rc << "(" << ui_of(f) << "& ui);   // ui: the form whose hooks the row calls\n"
          << "        void bind(const Glib::RefPtr<" << model_item(*md) << ">& item);   // show this row's item\n"
          << "        void unbind();                                     // the row is free again\n";
        std::vector<const Node*> ms;
        walk(row, [&](const Node& n, const Node* parent) { if (parent) ms.push_back(&n); });
        if (!ms.empty()) {
            std::size_t width = 0;
            for (auto* m : ms) width = std::max(width, find_widget(m->type)->gtk_class.size());
            h << "\n";
            std::size_t idw = 0;
            for (auto* m : ms) idw = std::max(idw, m->id.size());
            for (auto* m : ms) {
                const std::string decl = "        " + pad(find_widget(m->type)->gtk_class, width) + " m_" + m->id + ";";
                h << (bound_field(*m).empty() ? decl : pad(decl, 8 + width + 4 + idw) + "   // shows " + bound_field(*m))
                  << "\n";
            }
        }
        h << "\n    private:\n"
          << "        " << ui_of(f) << "* m_ui;\n"
          << "        std::shared_ptr<bool> m_alive;   // false once the form is going: no hook runs then\n"
          << "        Glib::RefPtr<" << model_item(*md) << "> m_item;   // the item shown now (null between items)\n"
          << "        bool m_binding = false;          // bind() is filling the widgets: not the user\n"
          << "    };\n\n";
    }
    return h.str();
}

static std::string row_classes_source(const Form& f, const std::string& ui) {
    std::ostringstream c;
    for (const auto& [v, md] : list_views(f)) {
        const Node& row = *view_row(*v);
        const std::string rc = row_class(*v), q = ui + "::" + rc;
        std::vector<std::string> lines;
        build_node(f, row, true, lines);
        c << "// " << v->id << "'s row: built once per visible row -- properties, then packing,\n"
          << "// then what its widgets do (each hands the form THIS row's item).\n"
          << q << "::" << rc << "(" << ui_of(f) << "& ui) : m_ui(&ui), m_alive(ui.m_rows_alive) {\n";
        for (const auto& l : lines) c << (l.empty() ? "" : "    " + l) << "\n";
        c << row_wiring(f, *v, *md);
        c << "}\n\n"
          << "void " << q << "::unbind() { m_item.reset(); }\n\n"
          << "void " << q << "::bind(const Glib::RefPtr<" << model_item(*md) << ">& item) {\n"
          << "    m_item = item;\n"
          << "    m_binding = true;   // the setters below fire the widgets' signals -- that's not the user\n";
        bool any = false;
        walk(row, [&](const Node& n, const Node* parent) {
            const std::string b = bound_field(n);
            if (b.empty()) return;
            for (const auto& x : md->fields)
                if (x.name == b) { c << "    " << bind_line(n, !parent, x) << "\n"; any = true; }
        });
        if (!any) c << "    // nothing in the row binds a field yet\n";
        c << "    m_binding = false;\n"
          << "}\n\n";
    }
    return c.str();
}

// s006 / s013 -- a model's item class: a Glib::Object with a member per field
// and a unique id(). Nested in <Form>Ui (indent "    ") for a form's own
// model; at namespace level in generated/Models for a shared one.
static std::string item_decl(const ModelDef& m, const std::string& in) {
    std::ostringstream h;
    const std::string it = model_item(m);
    std::string params;
    for (const auto& x : m.fields)
        params += (x.type == "string" ? "const std::string& " : field_cpp_type(x.type) + " ") + x.name + " = {}, ";
    h << in << "class " << it << " : public Glib::Object {\n"
      << in << "public:\n"
      << in << "    static Glib::RefPtr<" << it << "> create(" << params << "std::uint64_t id = 0);\n"
      << in << "    ~" << it << "() override { ids().erase(m_id); }\n"
      << in << "    std::uint64_t id() const { return m_id; }\n"
      << in << "    static bool id_taken(std::uint64_t id) { return ids().count(id) != 0; }\n\n";
    std::size_t width = 0;
    for (const auto& x : m.fields) width = std::max(width, field_cpp_type(x.type).size());
    for (const auto& x : m.fields)
        h << in << "    " << pad(field_cpp_type(x.type), width) << " " << x.name
          << (x.type == "string" ? "" : x.type == "bool" ? " = false" : " = 0") << ";\n";
    h << "\n" << in << "protected:\n"
      << in << "    " << it << "() = default;\n"
      << in << "private:\n"
      << in << "    std::uint64_t m_id = 0;\n"
      << in << "    static std::set<std::uint64_t>& ids() { static std::set<std::uint64_t> s; return s; }\n"
      << in << "    static std::uint64_t& next() { static std::uint64_t n = 1; return n; }\n"
      << in << "};\n\n";
    return h.str();
}

static std::string item_def(const ModelDef& m, const std::string& qual) {
    std::ostringstream c;
    const std::string it = model_item(m), q = qual + it;
    std::string params;
    for (const auto& x : m.fields)
        params += (x.type == "string" ? "const std::string& " : field_cpp_type(x.type) + " ") + x.name + ", ";
    c << "// " << it << ": an automatic id, or yours -- never one that's taken.\n"
      << "Glib::RefPtr<" << q << "> " << q << "::create(" << params << "std::uint64_t id) {\n"
      << "    if (id != 0 && ids().count(id)) {\n"
      << "        if (auto lg = log::get(log::Area::Ui)) lg->error(" << cpp_string(it + ": id {} is taken -- not created") << ", id);\n"
      << "        return {};\n"
      << "    }\n"
      << "    if (id == 0) {\n"
      << "        while (ids().count(next())) ++next();\n"
      << "        id = next()++;\n"
      << "    } else if (id >= next()) {\n"
      << "        next() = id + 1;   // the counter goes on past yours\n"
      << "    }\n"
      << "    auto item = Glib::make_refptr_for_instance<" << it << ">(new " << it << "());\n"
      << "    item->m_id = id;\n"
      << "    ids().insert(id);\n";
    for (const auto& x : m.fields) c << "    item->" << x.name << " = " << x.name << ";\n";
    c << "    return item;\n"
      << "}\n\n";
    return c.str();
}

// s013 -- the project's models this form's views show (each once, in order).
static std::vector<const ModelDef*> shared_used(const Form& f) {
    std::vector<const ModelDef*> out;
    walk_members(f.root, [&](const Node& n, const Node*) {
        const auto it = n.props.find("model");
        if (it == n.props.end() || !std::holds_alternative<std::string>(it->second)) return;
        const auto& name = std::get<std::string>(it->second);
        for (const auto& m : f.models) if (m.name == name) return;   // the form's own wins (validate refuses both)
        for (const auto& m : f.shared)
            if (m.name == name && std::find(out.begin(), out.end(), &m) == out.end()) out.push_back(&m);
    });
    return out;
}

std::vector<OutFile> generate_models(const std::vector<ModelDef>& models, const AppInfo& app) {
    if (models.empty()) return {};
    std::ostringstream h;
    h << "// " << kGeneratedMarker << " from mortimer.json's models -- DO NOT EDIT.\n"
      << "// The project's SHARED models: one item class each, used by every form that\n"
      << "// shows it (a form says `TaskItem`; its Ui class has a using for it). Ids are\n"
      << "// unique per type across the whole app -- one set, not one per form.\n"
      << "#pragma once\n"
      << "#include <glibmm/object.h>\n#include <glibmm/refptr.h>\n\n#include <cstdint>\n#include <set>\n#include <string>\n\n"
      << "namespace " << app.ns << "::model {\n\n";
    for (const auto& m : models) h << item_decl(m, "");
    h << "}  // namespace " << app.ns << "::model\n";
    std::ostringstream c;
    c << "// " << kGeneratedMarker << " from mortimer.json's models -- DO NOT EDIT.\n"
      << "#include \"generated/Models.hpp\"\n#include \"Log.hpp\"\n\n"
      << "namespace " << app.ns << "::model {\n\n";
    for (const auto& m : models) c << item_def(m, "");
    c << "}  // namespace " << app.ns << "::model\n";
    return {{"generated/Models.hpp", h.str()}, {"generated/Models.cpp", c.str()}};
}

std::vector<OutFile> generate_form(const Form& f, const AppInfo& app) {
    const WidgetSpec* rootw = find_widget(f.root.type);
    const std::string ui = f.name + "Ui";
    const auto hooks = hooks_of(f);
    const std::string reg = f.root.id;   // registry prefix

    // Members: every node but the root, pre-order (= init-list order).
    std::vector<const Node*> members;
    walk_members(f.root, [&](const Node& n, const Node* parent) {
        if (parent) members.push_back(&n);
    });

    // ── the header ──────────────────────────────────────────────────────────
    std::ostringstream h;
    h << header_banner(f, "The widgets and the hooks of " + f.name + ".") << "#pragma once\n"
      << "#include \"generated/Widgets.hpp\"\n\n"
      << "#include <" << rootw->header << ">\n"
      << (f.actions.empty() ? "" : "#include <giomm/simpleactiongroup.h>\n")
      << (f.files.empty() ? "" : "#include <giomm/cancellable.h>\n")
      << (f.models.empty() ? "" : "#include <glibmm/object.h>\n#include <glibmm/refptr.h>\n#include <sigc++/signal.h>\n#include <cstdint>\n#include <set>\n#include <string>\n")
      << (shared_used(f).empty() ? "" : "#include \"generated/Models.hpp\"\n")
      << "#include <sigc++/connection.h>\n"
      << (f.files.empty() ? "" : "#include <map>\n#include <memory>\n#include <string>\n")
      << (opens_any(f) || !list_views(f).empty() ? "#include <memory>\n" : "")
      << "#include <vector>\n\n"
      << opens_forward(f, app)
      << "namespace " << app.ns << "::ui {\n\n"
      << "class " << ui << " : public " << rootw->gtk_class << " {\n"
      << "public:\n"
      << "    " << ui << "();\n"
      << "    ~" << ui << "() override;\n\n"
      << "    " << ui << "(const " << ui << "&) = delete;\n"
      << "    " << ui << "& operator=(const " << ui << "&) = delete;\n\n"
      << (remembers(f)
              ? "    // s008: the window remembers. It saves itself when it leaves the screen\n"
                "    // (closed, hidden); call this to save sooner. Restored in the constructor.\n"
                "    void save_window_state();\n\n"
              : "")
      << (f.root.type == "Dialog"
              ? "    // A dialog: make it transient for `parent` and show it. Built once, it hides\n"
                "    // on close (the X), so calling this again re-presents the same window.\n"
                "    void present_for(Gtk::Window& parent) {\n"
                "        set_transient_for(parent);\n"
                "        present();\n"
                "    }\n\n"
              : "");
    if (!f.files.empty()) {
        h << "    // ── file dialogs ── call one (from a hook, a button, an action); it opens over\n"
          << "    // this window and RETURNS AT ONCE. The answer arrives later, at its hook.\n"
          << "    // `initial`: a folder to start in, a file to start on, or (save) a bare name.\n";
        for (const auto& d : f.files) {
            std::string answer = file_chosen_hook(d) + (d.mode == "open_multiple" ? "(paths)" : "(path)");
            if (d.cancel) answer += " / " + file_cancelled_hook(d) + "()";
            h << "    void " << file_chooser(d) << "(const std::string& initial = {});   // "
              << d.mode << " -> " << answer << "\n";
        }
        h << "\n";
    }
    if (!f.models.empty()) {
        h << "    // ── models ── the row types. Item::create(fields...) gives each a fresh id();\n"
          << "    // pass your own (a database key) as the last argument. Ids are unique per\n"
          << "    // type: a taken one is refused -- create() returns null and logs an error.\n"
          << "    // An id is free again when its item is destroyed. (Main thread only.)\n";
        for (const auto& m : f.models) h << item_decl(m, "    ");
    }
    if (const auto used = shared_used(f); !used.empty()) {
        h << "    // ── shared models ── the project's (generated/Models.hpp): one class for every\n"
          << "    // form, so a row the main window lists is the row a dialog edits.\n";
        for (const auto* m : used)
            h << "    using " << model_item(*m) << " = ::" << app.ns << "::model::" << model_item(*m) << ";\n";
        h << "\n";
    }
    h << row_classes_header(f);
    h << "protected:\n";
    if (hooks.empty()) {
        h << "    // ── hooks: none ticked in the form yet ──\n\n";
    } else {
        h << "    // ── hooks ── override these in " << f.name
          << ". An unhooked one logs a warning the\n"
          << "    // first time it fires; a REQUIRED one is pure virtual -- " << f.name
          << " must write it.\n";
        std::size_t width = 0;
        for (const auto& k : hooks) width = std::max(width, k.decl().size() + 13);
        for (const auto& k : hooks) {
            const std::string d = "    virtual " + k.decl() + (k.required ? " = 0;" : ";");
            h << pad(d, width + 4) << "// " << k.widget << " (" << k.type << ") " << k.signal
              << (k.required ? " -- REQUIRED" : "") << "\n";
        }
        h << "\n";
    }
    if (!members.empty()) {
        h << "    // ── widgets ── registry names \"" << reg << ".<id>\"\n";
        std::size_t width = 0;
        for (auto* m : members) width = std::max(width, m->type.size());
        for (auto* m : members)
            h << "    widgets::" << pad(m->type, width) << " m_" << m->id << ";\n";
        h << "\n";
    }
    for (auto* m : members) {
        const ModelDef* md = model_of(f, *m);
        if (!md) continue;
        h << "    // " << m->id << "'s rows: append " << model_item(*md) << "::create(...) here; the table follows\n"
          << "    Glib::RefPtr<Gio::ListStore<" << model_item(*md) << ">> m_" << m->id << "_store;\n"
          << "    Glib::RefPtr<Gtk::" << (view_selection(*m) == "multiple" ? "MultiSelection" :
                                        view_selection(*m) == "none" ? "NoSelection" : "SingleSelection")
          << "> m_" << m->id << "_selection;   // over the sorted rows\n\n";
    }
    h << "private:\n"
      << "    void build_ui();     // construct: properties, then packing, top-down\n"
      << "    void bind_hooks();   // every ticked signal -> its hook (last, so no setter fires one)\n"
      << (remembers(f) ? "    void restore_window_state();   // s008: after build_ui, before the hooks\n" : "")
      << "    std::vector<sigc::connection> m_hooks;   // cut first in the destructor\n"
      << edited_members(f, members)
      << (list_views(f).empty() ? "" :
          "    // s011: the rows' token -- the destructor sets it false, so a row being torn\n"
          "    // down with the form never calls a hook.\n"
          "    std::shared_ptr<bool> m_rows_alive = std::make_shared<bool>(true);\n")
      << (f.actions.empty() ? "" : rootw->type == "ApplicationWindow" ? "" :
          "    Glib::RefPtr<Gio::SimpleActionGroup> m_actions;   // \"win.*\" (a plain Window has no action map)\n")
      << opens_members(f, app)
      << (f.files.empty() ? "" :
          "    // s005: a file dialog that is up, by name (its Cancellable); and the token its\n"
          "    // answer checks first -- the destructor drops it, so an answer arriving after\n"
          "    // this window is gone is dropped, never delivered to a dead object.\n"
          "    std::map<std::string, Glib::RefPtr<Gio::Cancellable>> m_files;\n"
          "    std::shared_ptr<bool> m_alive = std::make_shared<bool>(true);\n")
      << "};\n\n"
      << "}  // namespace " << app.ns << "::ui\n";

    // ── the source ──────────────────────────────────────────────────────────
    std::ostringstream c;
    c << header_banner(f, "Construction, wiring, and the unhooked defaults of " + f.name + ".")
      << "#include \"generated/" << ui << ".hpp\"\n"
      << "#include \"generated/Hooks.hpp\"\n"
      << "#include \"generated/Style.hpp\"\n"
      << (remembers(f) ? "#include \"generated/WindowState.hpp\"\n" : "")
      << "#include \"Registry.hpp\"\n"
      << opens_includes(f)
      << (list_views(f).empty() ? "" : "\n#include <cmath>\n#include <cstdint>\n")
      << (f.actions.empty() ? "" :
          "\n#include <giomm/simpleaction.h>\n#include <gtkmm/shortcut.h>\n#include <gtkmm/shortcutaction.h>\n"
          "#include <gtkmm/shortcutcontroller.h>\n#include <gtkmm/shortcuttrigger.h>\n")
      << (f.models.empty() || !f.files.empty() ? "" : "\n#include \"Log.hpp\"\n")
      << (f.files.empty() ? "" :
          "\n#include \"Log.hpp\"\n\n#include <giomm/file.h>\n#include <giomm/liststore.h>\n"
          "#include <glibmm/fileutils.h>\n#include <gtkmm/error.h>\n#include <gtkmm/filedialog.h>\n"
          "#include <gtkmm/filefilter.h>\n")
      << "\n"
      << "namespace " << app.ns << "::ui {\n\n"
      << parse_helpers(f)
      << ui << "::" << ui << "()";
    for (std::size_t i = 0; i < members.size(); ++i)
        c << (i == 0 ? "\n    : " : "\n    , ") << "m_" << members[i]->id << "("
          << cpp_string(reg + "." + members[i]->id) << ")";
    c << " {\n"
      << "    style::ensure();   // the app's stylesheet, once (generated/Style.cpp)\n"
      << "    set_name(" << cpp_string(reg) << ");\n"
      << "    registry::add(" << cpp_string(reg) << ", this);\n"
      << "    build_ui();\n"
      << (remembers(f) ? "    restore_window_state();\n" : "")
      << "    bind_hooks();\n"
      << "}\n\n"
      << ui << "::~" << ui << "() {\n"
      << (remembers(f) ? "    if (get_visible()) save_window_state();   // deleted while still on screen (the unmap would come after the cut)\n" : "")
      << "    // Cut the hooks FIRST. " << f.name << " is already gone by now, and a signal the\n"
      << "    // teardown fires (a Stack changing page, a ListBox dropping its selection)\n"
      << "    // must not reach a hook -- a REQUIRED one is pure virtual here.\n"
      << "    for (auto& c : m_hooks) c.disconnect();\n"
      << (list_views(f).empty() ? "" : "    *m_rows_alive = false;   // and the list rows' (they go with their views)\n")
      << (f.files.empty() ? "" :
          "    // A file dialog still up: drop the token (its answer is now ignored) and\n"
          "    // cancel it (the dialog closes with the window).\n"
          "    m_alive.reset();\n"
          "    for (auto& [name, cancel] : m_files) if (cancel) cancel->cancel();\n")
      << "    registry::remove(this);\n"
      << "}\n\n"
      << state_functions(f, ui);
    for (const auto& m : f.models) c << item_def(m, ui + "::");
    c << row_classes_source(f, ui);
    c << "void " << ui << "::build_ui() {\n";
    std::vector<std::string> lines;
    build_node(f, f.root, true, lines);
    for (const auto& l : lines) c << (l.empty() ? "" : "    " + l) << "\n";
    c << "}\n\n"
      << "void " << ui << "::bind_hooks() {\n"
      << (remembers(f) ? "    // s008: leaving the screen saves where it was left. UNMAP, not hide: in GTK 4\n"
                         "    // a closed window that doesn't hide-on-close is destroyed without a hide,\n"
                         "    // but hiding and destroying both unmap it.\n"
                         "    m_hooks.push_back(signal_unmap().connect(sigc::mem_fun(*this, &" + ui + "::save_window_state)));\n"
                       : "");
    walk_members(f.root, [&](const Node& n, const Node* parent) {
        const WidgetSpec* w = find_widget(n.type);
        for (const auto& hk : n.signals) {
            const SignalSpec* s = find_signal(*w, hk.signal);
            const std::string obj = parent ? "m_" + n.id + "." : "";
            if (s->connect == "{model}") {   // s006: hand the hook the ROW, not a position
                const ModelDef* md = model_of(f, n);
                if (!md) continue;
                const std::string item = model_item(*md), sel = "m_" + n.id + "_selection";
                if (hk.signal == "edited") {   // s007: the cells emit it after writing the row
                    c << "    m_hooks.push_back(m_" << n.id << "_edited.connect(\n"
                      << "        sigc::mem_fun(*this, &" << ui << "::" << hook_name(n, hk) << ")));\n";
                    continue;
                }
                if (hk.signal == "selected" && view_selection(n) == "multiple")
                    c << "    m_hooks.push_back(" << sel << "->signal_selection_changed().connect([this](guint, guint) {\n"
                      << "        std::vector<Glib::RefPtr<" << item << ">> items;   // every picked row, in the order you see\n"
                      << "        const auto picked = " << sel << "->get_selection();\n"
                      << "        for (guint i = 0, n = static_cast<guint>(picked->get_size()); i < n; ++i)\n"
                      << "            if (auto it = std::dynamic_pointer_cast<" << item << ">(" << sel
                      << "->get_object(picked->get_nth(i))))\n"
                      << "                items.push_back(it);\n"
                      << "        " << hook_name(n, hk) << "(items);\n"
                      << "    }));\n";
                else if (hk.signal == "activated")
                    c << "    m_hooks.push_back(m_" << n.id << ".signal_activate().connect([this](guint position) {\n"
                      << "        " << hook_name(n, hk) << "(std::dynamic_pointer_cast<" << item << ">(" << sel
                      << "->get_object(position)));\n"
                      << "    }));\n";
                else
                    c << "    m_hooks.push_back(" << sel << "->signal_selection_changed().connect([this](guint, guint) {\n"
                      << "        " << hook_name(n, hk) << "(std::dynamic_pointer_cast<" << item << ">(" << sel
                      << "->get_selected_item()));\n"
                      << "    }));\n";
                continue;
            }
            c << "    m_hooks.push_back(" << obj << s->connect << ".connect(\n"
              << "        sigc::mem_fun(*this, &" << ui << "::" << hook_name(n, hk) << ")"
              << (s->before ? ", false" : "") << "));\n";
        }
    });
    if (!f.actions.empty()) {
        // s003: the form's actions. Each is a Gio action "win.<name>" whose
        // activate runs its hook; the keys go on a ShortcutController in the
        // BUBBLE phase, so a focused text box keeps its own keys (an
        // application accelerator would take them first -- docs/undo.md).
        const bool appwin = rootw->type == "ApplicationWindow";
        c << "\n    // ── actions ── \"win.<name>\": menus and buttons name them; the key is on the window\n";
        if (!appwin)
            c << "    m_actions = Gio::SimpleActionGroup::create();\n"
              << "    insert_action_group(\"win\", m_actions);\n";
        bool keys = false;
        for (const auto& a : f.actions) keys = keys || !a.accel.empty();
        if (keys) c << "    auto keys = Gtk::ShortcutController::create();\n";
        for (const auto& a : f.actions) {
            const std::string gio = gio_action_name(a.name);
            c << "    {\n"
              << "        auto a = Gio::SimpleAction::create(" << cpp_string(gio) << ");\n";
            if (a.opens.empty())
                c << "        m_hooks.push_back(a->signal_activate().connect(\n"
                  << "            [this](const Glib::VariantBase&) { " << action_hook(a) << "(); }));\n";
            else
                c << opens_activate(a, app);
            c
              << "        " << (appwin ? "add_action(a);" : "m_actions->add_action(a);") << "\n";
            if (!a.accel.empty())
                c << "        keys->add_shortcut(Gtk::Shortcut::create(Gtk::ShortcutTrigger::parse_string("
                  << cpp_string(a.accel) << "),\n"
                  << "                                                 Gtk::NamedAction::create(" << cpp_string("win." + gio) << ")));\n";
            c << "    }\n";
        }
        if (keys) c << "    add_controller(keys);\n";
    }
    if (hooks.empty()) c << "    // nothing ticked yet\n";
    c << "}\n";
    for (const auto& d : f.files) c << file_chooser_def(f, d, ui);

    bool any_default = false;
    for (const auto& k : hooks) any_default = any_default || !k.required;
    if (any_default) {
        c << "\n// ── unhooked defaults ── each one logs once, the first time it fires. Override\n"
          << "// the hook in " << f.name << " and this body is never reached.\n";
        for (const auto& k : hooks) {
            if (k.required) continue;
            c << "\n" << k.ret << " " << ui << "::" << k.name << "(" << unnamed_params(k.params)
              << ") {\n"
              << "    hooks::unhooked(" << cpp_string(f.name) << ", " << cpp_string(k.name) << ", "
              << cpp_string(k.widget) << ", " << cpp_string(k.signal) << ");\n";
            if (k.ret != "void") c << "    return " << k.ret_default << ";\n";
            c << "}\n";
        }
    }
    c << "\n}  // namespace " << app.ns << "::ui\n";

    return {{"generated/" + ui + ".hpp", h.str()}, {"generated/" + ui + ".cpp", c.str()}};
}

