std::string render_double(double v) {
    char buf[64];
    auto r = std::to_chars(buf, buf + sizeof buf, v);   // shortest round-trip
    std::string s(buf, r.ptr);
    if (s.find_first_of(".eEn") == std::string::npos) s += ".0";
    return s;
}

std::string render_list(const StringList& l) {
    std::string s = "std::vector<Glib::ustring>{";
    for (std::size_t i = 0; i < l.size(); ++i) s += (i ? ", " : "") + cpp_string(l[i]);
    return s + "}";
}

std::string render(const PropSpec& p, const Value& v) {
    switch (p.kind) {
        case PropKind::Bool:   return std::get<bool>(v) ? "true" : "false";
        case PropKind::Int:    return std::to_string(std::get<std::int64_t>(v));
        case PropKind::Double:
            return std::holds_alternative<std::int64_t>(v)
                       ? std::to_string(std::get<std::int64_t>(v)) + ".0"
                       : render_double(std::get<double>(v));
        case PropKind::String: return cpp_string(std::get<std::string>(v));
        case PropKind::Enum: {
            const auto& s = std::get<std::string>(v);
            for (const auto& [jv, cv] : p.values)
                if (jv == s) return cv;
            return "/*bad enum*/";
        }
        case PropKind::Ref:    return "m_" + std::get<std::string>(v);
        case PropKind::StringList: return render_list(std::get<StringList>(v));
    }
    return "";
}

std::string replace(std::string s, const std::string& from, const std::string& to) {
    for (std::size_t at = s.find(from); at != std::string::npos; at = s.find(from, at + to.size()))
        s.replace(at, from.size(), to);
    return s;
}

// The setter lines for one property. A StringList `{item}` setter repeats;
// a `{menu}` setter builds a Gio::Menu from "Label=action" rows (s003).
std::vector<std::string> setter_lines(const PropSpec& p, const Value& v, const std::string& obj) {
    std::vector<std::string> out;
    if (p.kind == PropKind::StringList && p.setter.find("{menu}") != std::string::npos) {
        out.push_back("{");
        out.push_back("    auto menu = Gio::Menu::create();");
        out.push_back("    auto section = Gio::Menu::create();");
        for (const auto& item : std::get<StringList>(v)) {
            const MenuEntry e = parse_menu_entry(item);
            if (e.separator) {
                out.push_back("    menu->append_section(section);");
                out.push_back("    section = Gio::Menu::create();");
            } else {
                out.push_back("    section->append(" + cpp_string(e.label) + ", " + cpp_string(e.action) + ");");
            }
        }
        out.push_back("    menu->append_section(section);");
        out.push_back("    " + obj + replace(p.setter, "{menu}", "menu") + ";");
        out.push_back("}");
        return out;
    }
    if (p.kind == PropKind::StringList && p.setter.find("{item}") != std::string::npos) {
        for (const auto& item : std::get<StringList>(v))
            out.push_back(obj + replace(p.setter, "{item}", cpp_string(item)) + ";");
    } else {
        out.push_back(obj + replace(replace(p.setter, "{v}", render(p, v)), "{list}",
                                     p.kind == PropKind::StringList ? render(p, v) : "") + ";");
    }
    return out;
}

Value default_value(const PropSpec& p) {
    if (p.kind == PropKind::Double) return std::stod(p.def);
    if (p.kind == PropKind::Int) return static_cast<std::int64_t>(std::stoll(p.def));
    if (p.kind == PropKind::Bool) return p.def == "true";
    return p.def;
}

// Every property the node sets, in CATALOG order (the order is meaning: a
// Scale's range before its value, use_markup before the label).
std::vector<std::string> prop_lines(const Node& n, const WidgetSpec& w, const std::string& obj) {
    std::vector<std::string> out;
    auto one = [&](const PropSpec& p) {
        auto it = n.props.find(p.name);
        if (it != n.props.end()) {
            for (auto& l : setter_lines(p, it->second, obj)) out.push_back(l);
        } else if (p.always) {
            for (auto& l : setter_lines(p, default_value(p), obj)) out.push_back(l);
        }
    };
    for (const auto& p : w.props) one(p);
    for (const auto& p : common_props()) one(p);
    return out;
}

std::string str_pack(const Node& c, const std::string& key, const std::string& fallback) {
    auto it = c.pack.find(key);
    return it != c.pack.end() && std::holds_alternative<std::string>(it->second)
               ? std::get<std::string>(it->second) : fallback;
}
std::int64_t int_pack(const Node& c, const std::string& key, std::int64_t fallback) {
    auto it = c.pack.find(key);
    return it != c.pack.end() && std::holds_alternative<std::int64_t>(it->second)
               ? std::get<std::int64_t>(it->second) : fallback;
}
const bool* bool_pack(const Node& c, const std::string& key) {
    auto it = c.pack.find(key);
    return it != c.pack.end() && std::holds_alternative<bool>(it->second)
               ? &std::get<bool>(it->second) : nullptr;
}

// How child `c` goes into its parent.
std::vector<std::string> pack_lines(const WidgetSpec& pw, const std::string& pobj, const Node& c) {
    const std::string m = "m_" + c.id;
    std::vector<std::string> out;
    switch (pw.children) {
        case ChildKind::Window:
            out.push_back(pobj + (str_pack(c, "slot", "") == "titlebar" ? "set_titlebar(" : "set_child(") +
                          m + ");");
            break;
        case ChildKind::Single:
            out.push_back(pobj + "set_child(" + m + ");");
            break;
        case ChildKind::Box:
        case ChildKind::ListBox:
            out.push_back(pobj + "append(" + m + ");");
            break;
        case ChildKind::Grid:
            out.push_back(pobj + "attach(" + m + ", " + std::to_string(int_pack(c, "column", 0)) + ", " +
                          std::to_string(int_pack(c, "row", 0)) + ", " +
                          std::to_string(int_pack(c, "width", 1)) + ", " +
                          std::to_string(int_pack(c, "height", 1)) + ");");
            break;
        case ChildKind::Paned: {
            const std::string side = str_pack(c, "slot", "start");
            out.push_back(pobj + "set_" + side + "_child(" + m + ");");
            if (auto r = bool_pack(c, "resize"))
                out.push_back(pobj + "set_resize_" + side + "_child(" + (*r ? "true" : "false") + ");");
            if (auto s = bool_pack(c, "shrink"))
                out.push_back(pobj + "set_shrink_" + side + "_child(" + (*s ? "true" : "false") + ");");
            break;
        }
        case ChildKind::Stack: {
            std::string call = pobj + "add(" + m + ", " + cpp_string(str_pack(c, "name", c.id)) + ", " +
                               cpp_string(str_pack(c, "title", c.id)) + ")";
            const std::string icon = str_pack(c, "icon_name", "");
            out.push_back(icon.empty() ? call + ";" : call + "->set_icon_name(" + cpp_string(icon) + ");");
            break;
        }
        case ChildKind::HeaderBar: {
            const std::string slot = str_pack(c, "slot", "start");
            out.push_back(pobj + (slot == "title" ? "set_title_widget(" : slot == "end" ? "pack_end(" : "pack_start(") +
                          m + ");");
            break;
        }
        case ChildKind::None:
            break;
    }
    return out;
}

void build_node(const Node& n, bool is_root, std::vector<std::string>& lines) {
    const WidgetSpec* w = find_widget(n.type);
    const std::string obj = is_root ? "" : "m_" + n.id + ".";
    auto props = prop_lines(n, *w, obj);
    for (auto& l : props) lines.push_back(l);
    for (const auto& c : n.children) {
        lines.push_back("");
        lines.push_back("// " + c.id + " (" + c.type + ")");
        build_node(c, false, lines);
        for (auto& l : pack_lines(*w, obj, c)) lines.push_back(l);
    }
}

std::string unnamed_params(const std::string& params) {
    // "Gtk::ListBoxRow* row" -> "Gtk::ListBoxRow* /*row*/" (an unused-parameter-clean default)
    std::string out;
    std::stringstream ss(params);
    std::string one;
    while (std::getline(ss, one, ',')) {
        while (!one.empty() && one.front() == ' ') one.erase(0, 1);
        auto sp = one.find_last_of(" *&");
        std::string type = one.substr(0, sp + 1), name = one.substr(sp + 1);
        out += (out.empty() ? "" : ", ") + type + "/*" + name + "*/";
    }
    return out;
}

std::string pad(std::string s, std::size_t width) {
    if (s.size() < width) s.append(width - s.size(), ' ');
    return s;
}

