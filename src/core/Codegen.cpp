std::vector<OutFile> generate_support(const AppInfo& app) {
    std::set<std::string> headers;
    std::ostringstream w;
    w << "// " << kGeneratedMarker << " -- DO NOT EDIT.\n"
      << "// The Named<W> alias for every widget Mortimer can place, so a generated form\n"
      << "// declares `widgets::Button m_save;` and the name is mandatory by construction.\n"
      << "#pragma once\n"
      << "#include \"widgets/Named.hpp\"\n\n";
    for (const auto& s : catalog()) {
        if (s.root) continue;
        headers.insert(s.header);
        for (const auto& x : s.extra_headers) headers.insert(x);
    }
    for (const auto& x : headers) w << "#include <" << x << ">\n";
    w << "\nnamespace " << app.ns << "::widgets {\n\n";
    std::size_t width = 0;
    for (const auto& s : catalog()) width = std::max(width, s.type.size());
    for (const auto& s : catalog())
        if (!s.root) w << "using " << pad(s.type, width) << " = Named<" << s.gtk_class << ">;\n";
    w << "\n}  // namespace " << app.ns << "::widgets\n";

    std::ostringstream hh;
    hh << "// " << kGeneratedMarker << " -- DO NOT EDIT.\n"
       << "#pragma once\n\n"
       << "namespace " << app.ns << "::ui::hooks {\n\n"
       << "// An unhooked hook fired. Says so ONCE per hook, as a warning on the \"ui\" log\n"
       << "// area, naming the override to write. (The generated defaults call this.)\n"
       << "void unhooked(const char* form, const char* hook, const char* widget, const char* signal);\n\n"
       << "}  // namespace " << app.ns << "::ui::hooks\n";

    std::ostringstream hc;
    hc << "// " << kGeneratedMarker << " -- DO NOT EDIT.\n"
       << "#include \"generated/Hooks.hpp\"\n"
       << "#include \"Log.hpp\"\n\n"
       << "#include <set>\n#include <string>\n\n"
       << "namespace " << app.ns << "::ui::hooks {\n\n"
       << "void unhooked(const char* form, const char* hook, const char* widget, const char* signal) {\n"
       << "    static std::set<std::string> told;\n"
       << "    if (!told.insert(std::string(form) + \"::\" + hook).second) return;\n"
       << "    if (auto lg = log::get(log::Area::Ui))\n"
       << "        lg->warn(\"unhooked: {} {} -> override {}() in {} (generated/{}.hooks.txt)\",\n"
       << "                 widget, signal, hook, form, form);\n"
       << "}\n\n"
       << "}  // namespace " << app.ns << "::ui::hooks\n";

    std::ostringstream rd;
    rd << "<!-- " << kGeneratedMarker << " -- DO NOT EDIT. -->\n"
       << "# generated/ -- Mortimer's half\n\n"
       << "Everything in this folder is rewritten by `mortimer-gen generate` (and, later,\n"
       << "by Mortimer itself) from `forms/*.mort`. Don't edit it: the next generate puts\n"
       << "it back. A file here that no form produces any more is removed.\n\n"
       << "| File | What |\n|---|---|\n"
       << "| `<Form>Ui.hpp/.cpp` | the widgets, their properties and packing, the hooks |\n"
       << "| `<Form>.hooks.txt` | every hook: hooked, unhooked, missing, stale -- with lines to paste |\n"
       << "| `<Form>.hooks.json` | the same, for tools (and the stale-hook memory) |\n"
       << "| `Widgets.hpp` | the `Named<W>` aliases |\n"
       << "| `Hooks.hpp/.cpp` | the once-per-hook \"unhooked\" warning |\n"
       << "| `WindowState.hpp/.cpp` | where windows were left (a form's `remember`) |\n"
       << "| `Style.hpp/.cpp` | loads resources/<bin>.css, if the bundle has it |\n\n"
       << "Your half is `include/<Form>.hpp` + `src/<Form>.cpp`. Mortimer writes those\n"
       << "once, the first time a form is generated, and never again.\n";

    auto fill = [&](std::string t) {
        for (const auto& [from, to] : {std::pair<std::string, std::string>{"@NS@", app.ns}, {"@BIN@", app.bin},
                                       {"@MARK@", kGeneratedMarker}, {"@ID_PATH@", id_path(app.app_id)}}) {
            for (std::size_t at = 0; (at = t.find(from, at)) != std::string::npos; at += to.size())
                t.replace(at, from.size(), to);
        }
        return t;
    };
    return {{"generated/Widgets.hpp", w.str()},
            {"generated/Hooks.hpp", hh.str()},
            {"generated/Hooks.cpp", hc.str()},
            {"generated/WindowState.hpp", fill(kWindowStateHpp)},
            {"generated/WindowState.cpp", fill(kWindowStateCpp)},
            {"generated/Style.hpp", fill(kStyleHpp)},
            {"generated/Style.cpp", fill(kStyleCpp)},
            {"generated/README.md", rd.str()}};
}

