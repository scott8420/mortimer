// How child `c` goes into its parent.
std::vector<std::string> pack_lines(const WidgetSpec& pw, const std::string& pobj, const Node& c) {
    const std::string m = "m_" + c.id;
    std::vector<std::string> out;
    switch (pw.children) {
        case ChildKind::Window:
            out.push_back(pobj + (str_pack(c, "slot", "") == "titlebar" ? "set_titlebar(" : "set_child(") +
                          m + ");");
            break;
        case ChildKind::Single:
            out.push_back(pobj + "set_child(" + m + ");");
            break;
        case ChildKind::Box:
        case ChildKind::ListBox:
            out.push_back(pobj + "append(" + m + ");");
            break;
        case ChildKind::Grid:
            out.push_back(pobj + "attach(" + m + ", " + std::to_string(int_pack(c, "column", 0)) + ", " +
                          std::to_string(int_pack(c, "row", 0)) + ", " +
                          std::to_string(int_pack(c, "width", 1)) + ", " +
                          std::to_string(int_pack(c, "height", 1)) + ");");
            break;
        case ChildKind::Paned: {
            const std::string side = str_pack(c, "slot", "start");
            out.push_back(pobj + "set_" + side + "_child(" + m + ");");
            if (auto r = bool_pack(c, "resize"))
                out.push_back(pobj + "set_resize_" + side + "_child(" + (*r ? "true" : "false") + ");");
            if (auto s = bool_pack(c, "shrink"))
                out.push_back(pobj + "set_shrink_" + side + "_child(" + (*s ? "true" : "false") + ");");
            break;
        }
        case ChildKind::Stack: {
            std::string call = pobj + "add(" + m + ", " + cpp_string(str_pack(c, "name", c.id)) + ", " +
                               cpp_string(str_pack(c, "title", c.id)) + ")";
            const std::string icon = str_pack(c, "icon_name", "");
            out.push_back(icon.empty() ? call + ";" : call + "->set_icon_name(" + cpp_string(icon) + ");");
            break;
        }
        case ChildKind::HeaderBar: {
            const std::string slot = str_pack(c, "slot", "start");
            out.push_back(pobj + (slot == "title" ? "set_title_widget(" : slot == "end" ? "pack_end(" : "pack_start(") +
                          m + ");");
            break;
        }
        case ChildKind::None:
            break;
    }
    return out;
}

// s006 -- a ColumnView's model: the store (yours to fill), sorted by the
// clicked header, a single selection; then a column per field, each with a
