std::string cpp_string(const std::string& s) {
    std::string o = "\"";
    for (unsigned char c : s) {
        switch (c) {
            case '\\': o += "\\\\"; break;
            case '"':  o += "\\\""; break;
            case '\n': o += "\\n"; break;
            case '\t': o += "\\t"; break;
            case '\r': o += "\\r"; break;
            default:
                if (c < 0x20 || c == 0x7f) {
                    char b[8];
                    std::snprintf(b, sizeof b, "\\%03o", c);
                    o += b;
                } else {
                    o += static_cast<char>(c);
                }
        }
    }
    return o + "\"";
}

std::string Hook::decl() const { return ret + " " + name + "(" + params + ")"; }

std::vector<Hook> hooks_of(const Form& f) {
    std::vector<Hook> out;
    walk(f.root, [&](const Node& n, const Node*) {
        const WidgetSpec* w = find_widget(n.type);
        if (!w) return;
        for (const auto& h : n.signals) {
            const SignalSpec* s = find_signal(*w, h.signal);
            if (!s) continue;
            std::string params = s->params;
            if (params == "{item}") {   // s006: a row of the widget's model
                const auto it = n.props.find("model");
                const std::string item = it != n.props.end() && std::holds_alternative<std::string>(it->second)
                                             ? std::get<std::string>(it->second) + "Item" : "Glib::ObjectBase";
                params = h.signal == "selected" && view_selection(n) == "multiple"
                             ? "const std::vector<Glib::RefPtr<" + item + ">>& items"   // s007: every picked row
                             : "const Glib::RefPtr<" + item + ">& item";
            } else if (params == "{item_field}") {   // s007: an edited cell -- its row and its field
                const auto it = n.props.find("model");
                const std::string item = it != n.props.end() && std::holds_alternative<std::string>(it->second)
                                             ? std::get<std::string>(it->second) + "Item" : "Glib::ObjectBase";
                params = "const Glib::RefPtr<" + item + ">& item, const std::string& field";
            }
            out.push_back({hook_name(n, h), s->ret, params, s->ret_default, n.id, n.type,
                           h.signal, h.required});
        }
    });
    // s003: each action is a hook too (widget = the action's name, type "Action").
    for (const auto& a : f.actions)
        out.push_back({action_hook(a), "void", "", "", a.name, "Action", "activate", a.required});
    // s005: each file dialog's answer is a hook; Cancel is one too when ticked.
    for (const auto& d : f.files) {
        out.push_back({file_chosen_hook(d), "void",
                       d.mode == "open_multiple" ? "const std::vector<std::string>& paths"
                                                 : "const std::string& path",
                       "", d.name, "FileDialog", "chosen", d.required});
        if (d.cancel)
            out.push_back({file_cancelled_hook(d), "void", "", "", d.name, "FileDialog", "cancelled", false});
    }
    return out;
}

std::string override_decl(const Hook& h) {
    return "    " + h.decl() + " override;" + (h.required ? "   // REQUIRED" : "");
}

std::string override_def(const Hook& h, const std::string& cls) {
    std::string body = h.ret == "void" ? "" : "    return " + h.ret_default + ";\n";
    return h.ret + " " + cls + "::" + h.name + "(" + h.params + ") {\n" + body + "}\n";
}

// s005 -- one file dialog's choose_<name>(): build the Gtk::FileDialog, ask,
// and deliver the answer to its hook. The rules it keeps:
//   * one at a time -- asking again while it's up is refused (logged), not stacked;
//   * the answer checks the window's token first -- if the window went, nothing runs;
//   * Cancel / Escape (DialogError DISMISSED / CANCELLED) is not an error: it goes
//     to on_<name>_cancelled() when ticked, else nowhere; a real failure is logged
//     and then treated as a cancel, so a hook waiting on the answer always gets one.
static std::string file_chooser_def(const Form& f, const FileDef& d, const std::string& ui) {
    static const std::map<std::string, std::pair<std::string, std::string>> calls = {
        {"open", {"open", "open_finish"}},
        {"open_multiple", {"open_multiple", "open_multiple_finish"}},
        {"save", {"save", "save_finish"}},
        {"folder", {"select_folder", "select_folder_finish"}},
    };
    const auto call = calls.count(d.mode) ? calls.at(d.mode) : calls.at("open");
    const bool many = d.mode == "open_multiple";
    const std::string who = f.name + ": " + d.name;
    std::ostringstream c;
    c << "\n// ── file dialog " << d.name << " (" << d.mode << ") ──\n"
      << "void " << ui << "::" << file_chooser(d) << "(const std::string& initial) {\n"
      << "    if (m_files[" << cpp_string(d.name) << "]) {\n"
      << "        if (auto lg = log::get(log::Area::Ui)) lg->info(" << cpp_string(who + ": already open") << ");\n"
      << "        return;\n"
      << "    }\n"
      << "    auto dialog = Gtk::FileDialog::create();\n"
      << "    dialog->set_modal(true);\n";
    if (!d.title.empty()) c << "    dialog->set_title(" << cpp_string(d.title) << ");\n";
    if (!d.accept.empty()) c << "    dialog->set_accept_label(" << cpp_string(d.accept) << ");\n";
    if (!d.filters.empty() && d.mode != "folder") {
        c << "    {\n"
          << "        auto filters = Gio::ListStore<Gtk::FileFilter>::create();\n";
        for (const auto& row : d.filters) {
            const FileFilterRow r = parse_file_filter(row);
            if (!r.ok) continue;
            c << "        {\n"
              << "            auto ff = Gtk::FileFilter::create();\n"
              << "            ff->set_name(" << cpp_string(r.label) << ");\n";
            for (const auto& p : r.patterns)
                c << "            ff->" << (p.find('/') != std::string::npos ? "add_mime_type(" : "add_pattern(")
                  << cpp_string(p) << ");\n";
            c << "            filters->append(ff);\n"
              << "        }\n";
        }
        c << "        dialog->set_filters(filters);\n"
          << "    }\n";
    }
    c << "    if (!initial.empty()) {\n"
      << "        auto at = Gio::File::create_for_path(initial);\n"
      << "        if (Glib::file_test(initial, Glib::FileTest::IS_DIR)) dialog->set_initial_folder(at);\n";
    if (d.mode == "save")
        c << "        else if (initial.find('/') == std::string::npos) dialog->set_initial_name(initial);\n";
    c << "        else dialog->set_initial_file(at);   // its folder, and its name\n"
      << "    }\n"
      << "    auto cancel = Gio::Cancellable::create();\n"
      << "    m_files[" << cpp_string(d.name) << "] = cancel;\n"
      << "    dialog->" << call.first << "(*this, [this, alive = std::weak_ptr<bool>(m_alive), dialog]\n"
      << "                         (const Glib::RefPtr<Gio::AsyncResult>& result) {\n"
      << "        if (alive.expired()) return;   // the window went first: nobody to tell\n"
      << "        m_files.erase(" << cpp_string(d.name) << ");\n";
    if (many) c << "        std::vector<std::string> paths;\n";
    else      c << "        std::string path;\n";
    c << "        try {\n";
    if (many)
        c << "            for (const auto& file : dialog->" << call.second << "(result))\n"
          << "                if (file) paths.push_back(file->get_path().empty() ? file->get_uri() : file->get_path());\n";
    else
        c << "            if (auto file = dialog->" << call.second << "(result))\n"
          << "                path = file->get_path().empty() ? file->get_uri() : file->get_path();\n";
    c << "        } catch (const Gtk::DialogError& e) {\n"
      << "            if (e.code() == Gtk::DialogError::FAILED)\n"
      << "                if (auto lg = log::get(log::Area::Ui)) lg->error(" << cpp_string(who + ": {}") << ", e.what());\n"
      << "        } catch (const Glib::Error& e) {\n"
      << "            if (auto lg = log::get(log::Area::Ui)) lg->error(" << cpp_string(who + ": {}") << ", e.what());\n"
      << "        }\n"
      << "        if (!" << (many ? "paths" : "path") << ".empty()) " << file_chosen_hook(d)
      << "(" << (many ? "paths" : "path") << ");\n";
    if (d.cancel) c << "        else " << file_cancelled_hook(d) << "();\n";
    c << "    }, cancel);\n"
      << "}\n";
    return c.str();
}

std::vector<OutFile> generate_form(const Form& f, const AppInfo& app) {
    const WidgetSpec* rootw = find_widget(f.root.type);
    const std::string ui = f.name + "Ui";
    const auto hooks = hooks_of(f);
    const std::string reg = f.root.id;   // registry prefix

    // Members: every node but the root, pre-order (= init-list order).
    std::vector<const Node*> members;
    walk(f.root, [&](const Node& n, const Node* parent) {
        if (parent) members.push_back(&n);
    });

    // ── the header ──────────────────────────────────────────────────────────
    std::ostringstream h;
    h << header_banner(f, "The widgets and the hooks of " + f.name + ".") << "#pragma once\n"
      << "#include \"generated/Widgets.hpp\"\n\n"
      << "#include <" << rootw->header << ">\n"
      << (f.actions.empty() ? "" : "#include <giomm/simpleactiongroup.h>\n")
      << (f.files.empty() ? "" : "#include <giomm/cancellable.h>\n")
      << (f.models.empty() ? "" : "#include <glibmm/object.h>\n#include <glibmm/refptr.h>\n#include <sigc++/signal.h>\n#include <cstdint>\n#include <set>\n#include <string>\n")
      << "#include <sigc++/connection.h>\n"
      << (f.files.empty() ? "" : "#include <map>\n#include <memory>\n#include <string>\n")
      << "#include <vector>\n\n"
      << "namespace " << app.ns << "::ui {\n\n"
      << "class " << ui << " : public " << rootw->gtk_class << " {\n"
      << "public:\n"
      << "    " << ui << "();\n"
      << "    ~" << ui << "() override;\n\n"
      << "    " << ui << "(const " << ui << "&) = delete;\n"
      << "    " << ui << "& operator=(const " << ui << "&) = delete;\n\n"
      << (f.root.type == "Dialog"
              ? "    // A dialog: make it transient for `parent` and show it. Built once, it hides\n"
                "    // on close (the X), so calling this again re-presents the same window.\n"
                "    void present_for(Gtk::Window& parent) {\n"
                "        set_transient_for(parent);\n"
                "        present();\n"
                "    }\n\n"
              : "");
    if (!f.files.empty()) {
        h << "    // ── file dialogs ── call one (from a hook, a button, an action); it opens over\n"
          << "    // this window and RETURNS AT ONCE. The answer arrives later, at its hook.\n"
          << "    // `initial`: a folder to start in, a file to start on, or (save) a bare name.\n";
        for (const auto& d : f.files) {
            std::string answer = file_chosen_hook(d) + (d.mode == "open_multiple" ? "(paths)" : "(path)");
            if (d.cancel) answer += " / " + file_cancelled_hook(d) + "()";
            h << "    void " << file_chooser(d) << "(const std::string& initial = {});   // "
              << d.mode << " -> " << answer << "\n";
        }
        h << "\n";
    }
    if (!f.models.empty()) {
        h << "    // ── models ── the row types. Item::create(fields...) gives each a fresh id();\n"
          << "    // pass your own (a database key) as the last argument. Ids are unique per\n"
          << "    // type: a taken one is refused -- create() returns null and logs an error.\n"
          << "    // An id is free again when its item is destroyed. (Main thread only.)\n";
        for (const auto& m : f.models) {
            const std::string it = model_item(m);
            std::string params;
            for (const auto& x : m.fields)
                params += (x.type == "string" ? "const std::string& " : field_cpp_type(x.type) + " ") + x.name +
                          " = {}, ";
            h << "    class " << it << " : public Glib::Object {\n"
              << "    public:\n"
              << "        static Glib::RefPtr<" << it << "> create(" << params << "std::uint64_t id = 0);\n"
              << "        ~" << it << "() override { ids().erase(m_id); }\n"
              << "        std::uint64_t id() const { return m_id; }\n"
              << "        static bool id_taken(std::uint64_t id) { return ids().count(id) != 0; }\n\n";
            std::size_t width = 0;
            for (const auto& x : m.fields) width = std::max(width, field_cpp_type(x.type).size());
            for (const auto& x : m.fields)
                h << "        " << pad(field_cpp_type(x.type), width) << " " << x.name
                  << (x.type == "string" ? "" : x.type == "bool" ? " = false" : " = 0") << ";\n";
            h << "\n    protected:\n"
              << "        " << it << "() = default;\n"
              << "    private:\n"
              << "        std::uint64_t m_id = 0;\n"
              << "        static std::set<std::uint64_t>& ids() { static std::set<std::uint64_t> s; return s; }\n"
              << "        static std::uint64_t& next() { static std::uint64_t n = 1; return n; }\n"
              << "    };\n\n";
        }
    }
    h << "protected:\n";
    if (hooks.empty()) {
        h << "    // ── hooks: none ticked in the form yet ──\n\n";
    } else {
        h << "    // ── hooks ── override these in " << f.name
          << ". An unhooked one logs a warning the\n"
          << "    // first time it fires; a REQUIRED one is pure virtual -- " << f.name
          << " must write it.\n";
        std::size_t width = 0;
        for (const auto& k : hooks) width = std::max(width, k.decl().size() + 13);
        for (const auto& k : hooks) {
            const std::string d = "    virtual " + k.decl() + (k.required ? " = 0;" : ";");
            h << pad(d, width + 4) << "// " << k.widget << " (" << k.type << ") " << k.signal
              << (k.required ? " -- REQUIRED" : "") << "\n";
        }
        h << "\n";
    }
    if (!members.empty()) {
        h << "    // ── widgets ── registry names \"" << reg << ".<id>\"\n";
        std::size_t width = 0;
        for (auto* m : members) width = std::max(width, m->type.size());
        for (auto* m : members)
            h << "    widgets::" << pad(m->type, width) << " m_" << m->id << ";\n";
        h << "\n";
    }
    for (auto* m : members) {
        const ModelDef* md = model_of(f, *m);
        if (!md) continue;
        h << "    // " << m->id << "'s rows: append " << model_item(*md) << "::create(...) here; the table follows\n"
          << "    Glib::RefPtr<Gio::ListStore<" << model_item(*md) << ">> m_" << m->id << "_store;\n"
          << "    Glib::RefPtr<Gtk::" << (view_selection(*m) == "multiple" ? "MultiSelection" :
                                        view_selection(*m) == "none" ? "NoSelection" : "SingleSelection")
          << "> m_" << m->id << "_selection;   // over the sorted rows\n\n";
    }
    h << "private:\n"
      << "    void build_ui();     // construct: properties, then packing, top-down\n"
      << "    void bind_hooks();   // every ticked signal -> its hook (last, so no setter fires one)\n"
      << "    std::vector<sigc::connection> m_hooks;   // cut first in the destructor\n"
      << edited_members(f, members)
      << (f.actions.empty() ? "" : rootw->type == "ApplicationWindow" ? "" :
          "    Glib::RefPtr<Gio::SimpleActionGroup> m_actions;   // \"win.*\" (a plain Window has no action map)\n")
      << (f.files.empty() ? "" :
          "    // s005: a file dialog that is up, by name (its Cancellable); and the token its\n"
          "    // answer checks first -- the destructor drops it, so an answer arriving after\n"
          "    // this window is gone is dropped, never delivered to a dead object.\n"
          "    std::map<std::string, Glib::RefPtr<Gio::Cancellable>> m_files;\n"
          "    std::shared_ptr<bool> m_alive = std::make_shared<bool>(true);\n")
      << "};\n\n"
      << "}  // namespace " << app.ns << "::ui\n";

    // ── the source ──────────────────────────────────────────────────────────
    std::ostringstream c;
    c << header_banner(f, "Construction, wiring, and the unhooked defaults of " + f.name + ".")
      << "#include \"generated/" << ui << ".hpp\"\n"
      << "#include \"generated/Hooks.hpp\"\n"
      << "#include \"Registry.hpp\"\n"
      << (f.actions.empty() ? "" :
          "\n#include <giomm/simpleaction.h>\n#include <gtkmm/shortcut.h>\n#include <gtkmm/shortcutaction.h>\n"
          "#include <gtkmm/shortcutcontroller.h>\n#include <gtkmm/shortcuttrigger.h>\n")
      << (f.models.empty() || !f.files.empty() ? "" : "\n#include \"Log.hpp\"\n")
      << (f.files.empty() ? "" :
          "\n#include \"Log.hpp\"\n\n#include <giomm/file.h>\n#include <giomm/liststore.h>\n"
          "#include <glibmm/fileutils.h>\n#include <gtkmm/error.h>\n#include <gtkmm/filedialog.h>\n"
          "#include <gtkmm/filefilter.h>\n")
      << "\n"
      << "namespace " << app.ns << "::ui {\n\n"
      << parse_helpers(f)
      << ui << "::" << ui << "()";
    for (std::size_t i = 0; i < members.size(); ++i)
        c << (i == 0 ? "\n    : " : "\n    , ") << "m_" << members[i]->id << "("
          << cpp_string(reg + "." + members[i]->id) << ")";
    c << " {\n"
      << "    set_name(" << cpp_string(reg) << ");\n"
      << "    registry::add(" << cpp_string(reg) << ", this);\n"
      << "    build_ui();\n"
      << "    bind_hooks();\n"
      << "}\n\n"
      << ui << "::~" << ui << "() {\n"
      << "    // Cut the hooks FIRST. " << f.name << " is already gone by now, and a signal the\n"
      << "    // teardown fires (a Stack changing page, a ListBox dropping its selection)\n"
      << "    // must not reach a hook -- a REQUIRED one is pure virtual here.\n"
      << "    for (auto& c : m_hooks) c.disconnect();\n"
      << (f.files.empty() ? "" :
          "    // A file dialog still up: drop the token (its answer is now ignored) and\n"
          "    // cancel it (the dialog closes with the window).\n"
          "    m_alive.reset();\n"
          "    for (auto& [name, cancel] : m_files) if (cancel) cancel->cancel();\n")
      << "    registry::remove(this);\n"
      << "}\n\n"
      ;
    for (const auto& m : f.models) {
        const std::string it = model_item(m), q = ui + "::" + it;
        std::string params;
        for (const auto& x : m.fields)
            params += (x.type == "string" ? "const std::string& " : field_cpp_type(x.type) + " ") + x.name + ", ";
        c << "// " << it << ": an automatic id, or yours -- never one that's taken.\n"
          << "Glib::RefPtr<" << q << "> " << q << "::create(" << params << "std::uint64_t id) {\n"
          << "    if (id != 0 && ids().count(id)) {\n"
          << "        if (auto lg = log::get(log::Area::Ui)) lg->error(" << cpp_string(it + ": id {} is taken -- not created") << ", id);\n"
          << "        return {};\n"
          << "    }\n"
          << "    if (id == 0) {\n"
          << "        while (ids().count(next())) ++next();\n"
          << "        id = next()++;\n"
          << "    } else if (id >= next()) {\n"
          << "        next() = id + 1;   // the counter goes on past yours\n"
          << "    }\n"
          << "    auto item = Glib::make_refptr_for_instance<" << it << ">(new " << it << "());\n"
          << "    item->m_id = id;\n"
          << "    ids().insert(id);\n";
        for (const auto& x : m.fields) c << "    item->" << x.name << " = " << x.name << ";\n";
        c << "    return item;\n"
          << "}\n\n";
    }
    c << "void " << ui << "::build_ui() {\n";
    std::vector<std::string> lines;
    build_node(f, f.root, true, lines);
    for (const auto& l : lines) c << (l.empty() ? "" : "    " + l) << "\n";
    c << "}\n\n"
      << "void " << ui << "::bind_hooks() {\n";
    walk(f.root, [&](const Node& n, const Node* parent) {
        const WidgetSpec* w = find_widget(n.type);
        for (const auto& hk : n.signals) {
            const SignalSpec* s = find_signal(*w, hk.signal);
            const std::string obj = parent ? "m_" + n.id + "." : "";
            if (s->connect == "{model}") {   // s006: hand the hook the ROW, not a position
                const ModelDef* md = model_of(f, n);
                if (!md) continue;
                const std::string item = model_item(*md), sel = "m_" + n.id + "_selection";
                if (hk.signal == "edited") {   // s007: the cells emit it after writing the row
                    c << "    m_hooks.push_back(m_" << n.id << "_edited.connect(\n"
                      << "        sigc::mem_fun(*this, &" << ui << "::" << hook_name(n, hk) << ")));\n";
                    continue;
                }
                if (hk.signal == "selected" && view_selection(n) == "multiple")
                    c << "    m_hooks.push_back(" << sel << "->signal_selection_changed().connect([this](guint, guint) {\n"
                      << "        std::vector<Glib::RefPtr<" << item << ">> items;   // every picked row, in the order you see\n"
                      << "        const auto picked = " << sel << "->get_selection();\n"
                      << "        for (guint i = 0, n = static_cast<guint>(picked->get_size()); i < n; ++i)\n"
                      << "            if (auto it = std::dynamic_pointer_cast<" << item << ">(" << sel
                      << "->get_object(picked->get_nth(i))))\n"
                      << "                items.push_back(it);\n"
                      << "        " << hook_name(n, hk) << "(items);\n"
                      << "    }));\n";
                else if (hk.signal == "activated")
                    c << "    m_hooks.push_back(m_" << n.id << ".signal_activate().connect([this](guint position) {\n"
                      << "        " << hook_name(n, hk) << "(std::dynamic_pointer_cast<" << item << ">(" << sel
                      << "->get_object(position)));\n"
                      << "    }));\n";
                else
                    c << "    m_hooks.push_back(" << sel << "->signal_selection_changed().connect([this](guint, guint) {\n"
                      << "        " << hook_name(n, hk) << "(std::dynamic_pointer_cast<" << item << ">(" << sel
                      << "->get_selected_item()));\n"
                      << "    }));\n";
                continue;
            }
            c << "    m_hooks.push_back(" << obj << s->connect << ".connect(\n"
              << "        sigc::mem_fun(*this, &" << ui << "::" << hook_name(n, hk) << ")"
              << (s->before ? ", false" : "") << "));\n";
        }
    });
    if (!f.actions.empty()) {
        // s003: the form's actions. Each is a Gio action "win.<name>" whose
        // activate runs its hook; the keys go on a ShortcutController in the
        // BUBBLE phase, so a focused text box keeps its own keys (an
        // application accelerator would take them first -- docs/undo.md).
        const bool appwin = rootw->type == "ApplicationWindow";
        c << "\n    // ── actions ── \"win.<name>\": menus and buttons name them; the key is on the window\n";
        if (!appwin)
            c << "    m_actions = Gio::SimpleActionGroup::create();\n"
              << "    insert_action_group(\"win\", m_actions);\n";
        bool keys = false;
        for (const auto& a : f.actions) keys = keys || !a.accel.empty();
        if (keys) c << "    auto keys = Gtk::ShortcutController::create();\n";
        for (const auto& a : f.actions) {
            const std::string gio = gio_action_name(a.name);
            c << "    {\n"
              << "        auto a = Gio::SimpleAction::create(" << cpp_string(gio) << ");\n"
              << "        m_hooks.push_back(a->signal_activate().connect(\n"
              << "            [this](const Glib::VariantBase&) { " << action_hook(a) << "(); }));\n"
              << "        " << (appwin ? "add_action(a);" : "m_actions->add_action(a);") << "\n";
            if (!a.accel.empty())
                c << "        keys->add_shortcut(Gtk::Shortcut::create(Gtk::ShortcutTrigger::parse_string("
                  << cpp_string(a.accel) << "),\n"
                  << "                                                 Gtk::NamedAction::create(" << cpp_string("win." + gio) << ")));\n";
            c << "    }\n";
        }
        if (keys) c << "    add_controller(keys);\n";
    }
    if (hooks.empty()) c << "    // nothing ticked yet\n";
    c << "}\n";
    for (const auto& d : f.files) c << file_chooser_def(f, d, ui);

    bool any_default = false;
    for (const auto& k : hooks) any_default = any_default || !k.required;
    if (any_default) {
        c << "\n// ── unhooked defaults ── each one logs once, the first time it fires. Override\n"
          << "// the hook in " << f.name << " and this body is never reached.\n";
        for (const auto& k : hooks) {
            if (k.required) continue;
            c << "\n" << k.ret << " " << ui << "::" << k.name << "(" << unnamed_params(k.params)
              << ") {\n"
              << "    hooks::unhooked(" << cpp_string(f.name) << ", " << cpp_string(k.name) << ", "
              << cpp_string(k.widget) << ", " << cpp_string(k.signal) << ");\n";
            if (k.ret != "void") c << "    return " << k.ret_default << ";\n";
            c << "}\n";
        }
    }
    c << "\n}  // namespace " << app.ns << "::ui\n";

    return {{"generated/" + ui + ".hpp", h.str()}, {"generated/" + ui + ".cpp", c.str()}};
}

std::vector<OutFile> generate_support(const AppInfo& app) {
    std::set<std::string> headers;
    std::ostringstream w;
    w << "// " << kGeneratedMarker << " -- DO NOT EDIT.\n"
      << "// The Named<W> alias for every widget Mortimer can place, so a generated form\n"
      << "// declares `widgets::Button m_save;` and the name is mandatory by construction.\n"
      << "#pragma once\n"
      << "#include \"widgets/Named.hpp\"\n\n";
    for (const auto& s : catalog()) {
        if (s.root) continue;
        headers.insert(s.header);
        for (const auto& x : s.extra_headers) headers.insert(x);
    }
    for (const auto& x : headers) w << "#include <" << x << ">\n";
    w << "\nnamespace " << app.ns << "::widgets {\n\n";
    std::size_t width = 0;
    for (const auto& s : catalog()) width = std::max(width, s.type.size());
    for (const auto& s : catalog())
        if (!s.root) w << "using " << pad(s.type, width) << " = Named<" << s.gtk_class << ">;\n";
    w << "\n}  // namespace " << app.ns << "::widgets\n";

    std::ostringstream hh;
    hh << "// " << kGeneratedMarker << " -- DO NOT EDIT.\n"
       << "#pragma once\n\n"
       << "namespace " << app.ns << "::ui::hooks {\n\n"
       << "// An unhooked hook fired. Says so ONCE per hook, as a warning on the \"ui\" log\n"
       << "// area, naming the override to write. (The generated defaults call this.)\n"
       << "void unhooked(const char* form, const char* hook, const char* widget, const char* signal);\n\n"
       << "}  // namespace " << app.ns << "::ui::hooks\n";

    std::ostringstream hc;
    hc << "// " << kGeneratedMarker << " -- DO NOT EDIT.\n"
       << "#include \"generated/Hooks.hpp\"\n"
       << "#include \"Log.hpp\"\n\n"
       << "#include <set>\n#include <string>\n\n"
       << "namespace " << app.ns << "::ui::hooks {\n\n"
       << "void unhooked(const char* form, const char* hook, const char* widget, const char* signal) {\n"
       << "    static std::set<std::string> told;\n"
       << "    if (!told.insert(std::string(form) + \"::\" + hook).second) return;\n"
       << "    if (auto lg = log::get(log::Area::Ui))\n"
       << "        lg->warn(\"unhooked: {} {} -> override {}() in {} (generated/{}.hooks.txt)\",\n"
       << "                 widget, signal, hook, form, form);\n"
       << "}\n\n"
       << "}  // namespace " << app.ns << "::ui::hooks\n";

    std::ostringstream rd;
    rd << "<!-- " << kGeneratedMarker << " -- DO NOT EDIT. -->\n"
       << "# generated/ -- Mortimer's half\n\n"
       << "Everything in this folder is rewritten by `mortimer-gen generate` (and, later,\n"
       << "by Mortimer itself) from `forms/*.mort`. Don't edit it: the next generate puts\n"
       << "it back. A file here that no form produces any more is removed.\n\n"
       << "| File | What |\n|---|---|\n"
       << "| `<Form>Ui.hpp/.cpp` | the widgets, their properties and packing, the hooks |\n"
       << "| `<Form>.hooks.txt` | every hook: hooked, unhooked, missing, stale -- with lines to paste |\n"
       << "| `<Form>.hooks.json` | the same, for tools (and the stale-hook memory) |\n"
       << "| `Widgets.hpp` | the `Named<W>` aliases |\n"
       << "| `Hooks.hpp/.cpp` | the once-per-hook \"unhooked\" warning |\n\n"
       << "Your half is `include/<Form>.hpp` + `src/<Form>.cpp`. Mortimer writes those\n"
       << "once, the first time a form is generated, and never again.\n";

    return {{"generated/Widgets.hpp", w.str()},
            {"generated/Hooks.hpp", hh.str()},
            {"generated/Hooks.cpp", hc.str()},
            {"generated/README.md", rd.str()}};
}

std::vector<OutFile> user_stubs(const Form& f, const AppInfo& app) {
    const auto hooks = hooks_of(f);
    const std::string ui = f.name + "Ui";

    std::ostringstream h;
    h << "#pragma once\n"
      << "#include \"generated/" << ui << ".hpp\"\n\n"
      << "// " << f.name << " -- YOUR half of the form. Mortimer wrote this file once and will\n"
      << "// never write it again: it is yours to edit.\n"
      << "//\n"
      << "// The other half, generated/" << ui << ".{hpp,cpp}, is rewritten whenever the\n"
      << "// form changes. It owns the widgets (m_<id>) and wires every ticked signal to a\n"
      << "// virtual hook. To hook a signal, override its hook here:\n"
      << "//   * unhooked  -> it logs a warning the first time it fires;\n"
      << "//   * REQUIRED  -> pure virtual: this class won't compile until you write it;\n"
      << "//   * removed   -> a hook you deleted from the form makes its `override` here a\n"
      << "//                  compile error, so a renamed button never leaves a dead handler.\n"
      << "// generated/" << f.name << ".hooks.txt lists every hook, with the lines to paste.\n"
      << "namespace " << app.ns << " {\n\n"
      << "class " << f.name << " : public ui::" << ui << " {\n"
      << "public:\n"
      << "    " << f.name << "();\n";
    if (!hooks.empty()) {
        h << "\nprotected:\n"
          << "    // ── hooks ──\n";
        for (const auto& k : hooks) h << override_decl(k) << "\n";
    }
    h << "};\n\n"
      << "}  // namespace " << app.ns << "\n";

    std::ostringstream c;
    c << "#include \"" << f.name << ".hpp\"\n"
      << "#include \"Log.hpp\"\n\n"
      << "namespace " << app.ns << " {\n\n"
      << f.name << "::" << f.name << "() {\n"
      << "    // " << ui << "'s constructor has run: every widget is built, packed and\n"
      << "    // wired. Fill in models, load state, set what the form can't express.\n"
      << "}\n";
    for (const auto& k : hooks) {
        c << "\n" << k.ret << " " << f.name << "::" << k.name << "(" << k.params << ") {\n";
        if (k.type == "FileDialog" && k.signal == "chosen")
            c << "    if (auto lg = log::get(log::Area::Ui)) lg->info(\"" << f.name << ": " << k.widget
              << " chosen {}\", " << (k.params.find("paths") != std::string::npos
                                           ? "std::to_string(paths.size()) + \" file(s)\"" : "path")
              << ");\n";
        else
            c << "    if (auto lg = log::get(log::Area::Ui)) lg->info(\"" << f.name << ": " << k.widget
              << " " << k.signal << "\");\n";
        if (k.ret != "void")
            c << "    return " << k.ret_default << ";"
              << (k.signal == "close_request" ? "   // true keeps the window open" : "") << "\n";
        c << "}\n";
    }
    c << "\n}  // namespace " << app.ns << "\n";

    return {{"include/" + f.name + ".hpp", h.str()}, {"src/" + f.name + ".cpp", c.str()}};
}

